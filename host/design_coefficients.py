"""Generate auditable Q1.15 17-tap windowed-sinc FIR coefficients.

This is a deterministic standard-library-only coefficient generator.
The checked-in text + SV include are its frozen outputs.
"""
from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path

TAPS = 17
FS = 30.0
CUTOFF = 2.5
SCALING = 1 << 15


def design() -> list[int]:
    center = (TAPS-1)//2
    fc = CUTOFF / FS
    raw: list[float] = []
    for k in range(TAPS):
        off = k-center
        ideal = 2*fc if off == 0 else math.sin(2*math.pi*fc*off)/(math.pi*off)
        window = 0.54 - 0.46 * math.cos(2*math.pi*k/(TAPS-1))
        raw.append(ideal*window)
    total = sum(raw)
    quantized = [round(v/total*SCALING) for v in raw]
    # Multiples of two at symmetric outer taps make a centre adjustment exact.
    quantized[center] += SCALING - sum(quantized)
    assert len(quantized) == TAPS
    assert quantized == quantized[::-1]
    assert sum(quantized) == SCALING
    assert all(-32768 <= c <= 32767 for c in quantized)
    return quantized


def generate(root: Path) -> None:
    coeffs = design()
    text = '# Q1.15 signed 16-bit; 17 taps; fs=30 fps; cutoff=2.5 Hz; Hamming window\n' + ''.join(f'{c}\n' for c in coeffs)
    coeff_path = root/'hardware'/'rtl'/'fir_coefficients.txt'
    coeff_path.write_bytes(text.encode('utf-8'))
    lines = [
        '// Generated by host/design_coefficients.py; DO NOT EDIT manually.',
        '// 17-tap symmetric Q1.15 FIR; fs=30 fps; nominal cutoff=2.5 Hz.',
        '// Actual integer coefficient list: hardware/rtl/fir_coefficients.txt',
        'function automatic logic signed [15:0] coeff_at(input logic [4:0] tap);',
        '  case (tap)',
    ]
    for k,c in enumerate(coeffs):
        val = f"16'sd{c}" if c >= 0 else f"-16'sd{-c}"
        lines.append(f"    5'd{k}: coeff_at = {val};")
    lines.extend(["    default: coeff_at = 16'sd0;", '  endcase', 'endfunction', ''])
    (root/'hardware'/'rtl'/'fir_coefficients.svh').write_bytes('\n'.join(lines).encode('utf-8'))
    print('coefficients:', coeffs)
    print('sum:', sum(coeffs), 'sha256:', hashlib.sha256(coeff_path.read_bytes()).hexdigest())
    # Show preliminary ideal coefficient response; not an RTL or FPGA measurement.
    for f in [0.0, .25, 1., 2.5, 5., 6., 10., 15.]:
        real = sum(c/SCALING*math.cos(2*math.pi*f*k/FS) for k,c in enumerate(coeffs))
        imag = -sum(c/SCALING*math.sin(2*math.pi*f*k/FS) for k,c in enumerate(coeffs))
        magnitude = math.hypot(real, imag)
        print(f'f={f:4.1f} Hz: {20*math.log10(max(magnitude,1e-15)):7.2f} dB')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    generate(parser.parse_args().root)
