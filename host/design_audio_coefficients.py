"""Deterministic 16 kHz mono speech low-pass ROM (17 taps, signed Q1.15).

This is NOT the 30 Hz camera-motion coefficient bank. The 3.2 kHz cutoff
attenuates high-frequency hiss, but is not a speech/noise separator.
"""
from __future__ import annotations
import math
from pathlib import Path

TAPS = 17
FS = 16000
CUTOFF_HZ = 3200
Q = 1 << 15


def design() -> tuple[int, ...]:
    fc = CUTOFF_HZ / FS
    mid = (TAPS - 1) // 2
    raw = []
    for i in range(TAPS):
        n = i - mid
        sinc = 2 * fc if n == 0 else math.sin(2 * math.pi * fc * n) / (math.pi * n)
        hann = 0.54 - 0.46 * math.cos(2 * math.pi * i / (TAPS - 1))
        raw.append(sinc * hann)
    scale = sum(raw)
    coeff = [round(x * Q / scale) for x in raw]
    coeff[mid] += Q - sum(coeff)
    assert coeff == coeff[::-1] and sum(coeff) == Q
    assert all(-(1 << 15) <= x < (1 << 15) for x in coeff)
    return tuple(coeff)


def generate(root: Path) -> None:
    coeff = design()
    p = root / 'hardware' / 'rtl' / 'audio_coefficients.txt'
    p.write_bytes(('# 16kHz speech LP 3200Hz, 17 taps, signed Q1.15, DC unity\n' +
                   ''.join(f'{x}\n' for x in coeff)).encode('utf-8'))
    lines = [
        '// Generated by host/design_audio_coefficients.py. Do not edit by hand.',
        '// 16 kHz audio, Hamming-window 3200 Hz LP FIR, 17 Q1.15 taps.',
        'function automatic logic signed [15:0] audio_coeff_at(input logic [4:0] tap);',
        '  case (tap)',
    ]
    for i, x in enumerate(coeff):
        lines.append(f"    5'd{i}: audio_coeff_at = " + (f"16'sd{x}" if x >= 0 else f"-16'sd{-x}") + ';')
    lines.extend(["    default: audio_coeff_at = 16'sd0;", '  endcase', 'endfunction', ''])
    (root/'hardware'/'rtl'/'audio_coefficients.svh').write_bytes('\n'.join(lines).encode('utf-8'))
    print('AUDIO_FIR_COEFFICIENTS_GENERATED',list(coeff),'sum',sum(coeff))


if __name__ == '__main__':
    generate(Path(__file__).resolve().parents[1])
